// ---------------- Renderer ----------------
function drawSprite(ctx, name, x, y, scale = 1, opts = {}) {
  const s = SPRITES[name];
  if (!s) return;
  const flip = opts.flip || false;
  const tint = opts.tint;

  for (let py = 0; py < s.h; py++) {
    const row = s.pixels[py];
    for (let px = 0; px < row.length; px++) {
      const ch = row[px];
      let color = s.palette[ch];
      if (!color) continue;
      if (tint && ch !== '0') color = tint;
      const drawX = flip ? x + (s.w - 1 - px) * scale : x + px * scale;
      ctx.fillStyle = color;
      ctx.fillRect(drawX, y + py * scale, scale, scale);
    }
  }
}

function spriteToDataURL(name, scale = 6, bg = null) {
  const s = SPRITES[name];
  if (!s) return '';
  const c = document.createElement('canvas');
  c.width = s.w * scale;
  c.height = s.h * scale;
  const ctx = c.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  if (bg) {
    ctx.fillStyle = bg;
    ctx.fillRect(0, 0, c.width, c.height);
  }
  drawSprite(ctx, name, 0, 0, scale);
  return c.toDataURL();
}

window.SPRITES = SPRITES;
window.drawSprite = drawSprite;
window.spriteToDataURL = spriteToDataURL;
